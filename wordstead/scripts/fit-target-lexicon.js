import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createBag } from '../src/core/bag.js';
import { loadAnalysisSource, loadBaseline, PROFILE_URL } from './letter-analysis-source.js';
import { analyzeRack } from '../src/analysis/rack.js';
import { measureFlexibility, METRIC_WEIGHTS } from '../src/analysis/statistics.js';
import { BAG_ID, BAG_SIGNATURE } from '../src/analysis/bag.js';
import { rackComposition, FLEXIBILITY_KEYS, LEXICAL_FEATURE_VERSION } from '../src/analysis/lexical-features.js';

export const MODEL_URL = new URL('../src/analysis/target-lexicon-v1.js', import.meta.url);
export const TRAINING = Object.freeze({ prefix: 'wordstead-3c3-fit-v1', count: 6000, ridge: 2 });

/** Deterministic ridge normal equations and Cholesky solve; Node development only. */
export function fitLexicon() {
  const { prepared } = loadAnalysisSource(), baseline = loadBaseline(prepared);
  const samples = Array.from({ length: TRAINING.count }, (_, index) => {
    const rack = createBag(`${TRAINING.prefix}:${index}`).bag.slice(0, 7);
    return { x: rackComposition(rack), y: measureFlexibility(analyzeRack(rack, prepared), baseline) };
  });
  const size = samples[0].x.length;
  const a = Array.from({ length: size }, () => new Float64Array(size));
  const b = FLEXIBILITY_KEYS.map(() => new Float64Array(size));
  for (const { x, y } of samples) {
    for (let i = 0; i < size; i += 1) {
      for (let j = 0; j <= i; j += 1) a[i][j] += x[i] * x[j];
      FLEXIBILITY_KEYS.forEach((key, k) => { b[k][i] += x[i] * y[key]; });
    }
  }
  for (let i = 0; i < size; i += 1) {
    a[i][i] += i === 0 ? 0 : TRAINING.ridge;
    for (let j = 0; j <= i; j += 1) {
      let value = a[i][j];
      for (let k = 0; k < j; k += 1) value -= a[i][k] * a[j][k];
      a[i][j] = i === j ? Math.sqrt(value) : value / a[j][j];
    }
  }
  const weights = b.map((rhs) => {
    const solution = new Float64Array(size), z = new Float64Array(size);
    for (let i = 0; i < size; i += 1) {
      let value = rhs[i];
      for (let j = 0; j < i; j += 1) value -= a[i][j] * z[j];
      z[i] = value / a[i][i];
    }
    for (let i = size - 1; i >= 0; i -= 1) {
      let value = z[i];
      for (let j = i + 1; j < size; j += 1) value -= a[j][i] * solution[j];
      solution[i] = value / a[i][i];
    }
    return [...solution].map((value) => Number(value.toFixed(9)));
  });
  const model = { schemaVersion: 1, methodVersion: 'rack-regression-v1', referenceMethod: 'rack-lexical-v1',
    featureVersion: LEXICAL_FEATURE_VERSION, identity: prepared.identity, bagId: BAG_ID, bagSignature: BAG_SIGNATURE,
    profileSha256: createHash('sha256').update(readFileSync(PROFILE_URL)).digest('hex'),
    training: TRAINING, metrics: FLEXIBILITY_KEYS, metricWeights: METRIC_WEIGHTS,
    baselineMean: baseline.capacities[7].flexibility.overall.mean, weights,
    notice: '../../data/letter-analysis/NOTICE.txt' };
  // Compact rows: this is a small coefficient table, never a dictionary or rack cache.
  return `// Generated by scripts/fit-target-lexicon.js. Derived from ESDB; see data/letter-analysis/NOTICE.txt.\n`
    + `export const TARGET_LEXICON = ${JSON.stringify(model, null, 2).replace(/\[\n\s+(-?[\d.]+[\s\S]*?)\n\s+\]/g,
      (match) => match.replace(/\s+/g, ' '))};\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    if (process.argv.slice(2).some((arg) => arg !== '--check') || process.argv.length > 3) throw new Error('Usage: node scripts/fit-target-lexicon.js [--check]');
    const source = fitLexicon();
    if (process.argv.includes('--check')) {
      if (readFileSync(MODEL_URL, 'utf8') !== source) throw new Error('Target lexicon differs; regenerate explicitly.');
    } else writeFileSync(MODEL_URL, source);
    console.log(`Target lexicon ${process.argv.includes('--check') ? 'verified' : 'generated'} (${Buffer.byteLength(source)} bytes).`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
