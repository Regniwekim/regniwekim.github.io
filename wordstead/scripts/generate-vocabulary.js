import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SOURCE, EXPORT_ARGS, transformExport } from './vocabulary-source.js';

const root = fileURLToPath(new URL('../', import.meta.url));
function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, SCOWL_OPTS: '', SCOWL_CACHE: '', SCOWL_DEBUG_SQL: 'False', PYTHONHASHSEED: '0' } });
  if (result.error || result.status !== 0) {
    throw new Error(`${command} failed: ${result.error?.message ?? result.stderr}`);
  }
  return result.stdout;
}

export function buildArtifacts(raw, copyright) {
  const notice = copyright.replaceAll('\r\n', '\n');
  if (!notice.startsWith('Copyright 2000-2026 by Kevin Atkinson\n')
    || !notice.includes('or word lists\ncreated from it, is hereby granted without fee')) {
    throw new Error('Unexpected upstream notice; review redistribution terms before generating.');
  }
  const { words, counts } = transformExport(raw);
  // Upstream explicitly says this first section suffices for this American size-60 list.
  const requiredNotice = notice.split('\n===\n')[0].trimEnd();
  const header = `# Wordstead vocabulary ${SOURCE.id}\n`
    + requiredNotice.split('\n').map((line) => `# ${line}`.trimEnd()).join('\n') + '\n';
  const artifact = `${header}${words.join('\n')}\n`;
  const sha256 = createHash('sha256').update(artifact).digest('hex');
  const manifest = { ...SOURCE, file: `${SOURCE.id}.txt`, count: words.length,
    bytes: Buffer.byteLength(artifact), sha256,
    integrity: `sha256-${createHash('sha256').update(artifact).digest('base64')}` };
  const report = { source: SOURCE, exportArgs: EXPORT_ARGS, counts,
    // SQL output order is not guaranteed across SQLite versions. Hash canonical records.
    sourceExportSha256: createHash('sha256').update(raw.replaceAll('\r\n', '\n')
      .slice(0, -1).split('\n').sort().join('\n') + '\n').digest('hex'),
    noticeSha256: createHash('sha256').update(notice).digest('hex'),
    output: manifest };
  return { artifact, notice, manifest, report };
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const sourceIndex = args.indexOf('--source');
  const pythonIndex = args.indexOf('--python');
  const allowed = new Set(['--source', '--python', '--check']);
  for (let index = 0; index < args.length; index += 1) {
    if (!allowed.has(args[index])) throw new Error(`Unknown argument: ${args[index]}`);
    if (args[index] !== '--check' && (!args[++index] || args[index].startsWith('--'))) {
      throw new Error('Missing argument value.');
    }
  }
  if (sourceIndex < 0) throw new Error('Usage: node scripts/generate-vocabulary.js --source <ESDB checkout> [--python python] [--check]');
  const source = resolve(args[sourceIndex + 1]);
  const python = pythonIndex < 0 ? 'python' : args[pythonIndex + 1];
  // Command-scoped trust applies only to the explicitly supplied source checkout.
  const git = ['-c', `safe.directory=${source.replaceAll('\\', '/')}`, '-C', source];
  if (run('git', [...git, 'rev-parse', 'HEAD'], root).trim() !== SOURCE.commit) {
    throw new Error(`Source must be pinned at ${SOURCE.commit}.`);
  }
  if (run('git', [...git, 'status', '--porcelain', '--untracked-files=no'], root).trim()) {
    throw new Error('Source has tracked modifications; use a clean pinned checkout.');
  }
  const temporary = mkdtempSync(join(tmpdir(), 'wordstead-vocabulary-'));
  try {
    const database = join(temporary, 'scowl.db');
    process.stdout.write('Building pinned ESDB database (Python + SQLite, development only)…\n');
    run(python, ['-X', 'utf8', 'combine.py', 'create-db', database], source);
    const raw = run(python, ['-X', 'utf8', 'scowl', '--db', database, ...EXPORT_ARGS], source);
    const result = buildArtifacts(raw, readFileSync(join(source, 'Copyright'), 'utf8'));
    const files = new Map([
      [join(root, 'vocabulary', result.manifest.file), result.artifact],
      [join(root, 'vocabulary', 'generation.json'), `${JSON.stringify(result.report, null, 2)}\n`],
      [join(root, 'src', 'vocabulary', 'manifest.js'), `// Generated by scripts/generate-vocabulary.js; do not edit.\nexport const VOCABULARY = Object.freeze(${JSON.stringify(result.manifest, null, 2)});\n`],
      [join(root, 'licenses', 'esdb', 'Copyright'), result.notice],
    ]);
    for (const [path, contents] of files) {
      if (check) {
        if (readFileSync(path, 'utf8') !== contents) throw new Error(`Generated file differs: ${path}`);
      } else {
        mkdirSync(resolve(path, '..'), { recursive: true });
        writeFileSync(path, contents);
      }
    }
    process.stdout.write(`${check ? 'Verified' : 'Generated'} ${result.manifest.count} words, ${result.manifest.bytes} bytes\nSHA-256 ${result.manifest.sha256}\n`);
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
